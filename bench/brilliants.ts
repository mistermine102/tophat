// (Brilliant) Benchmark: where do chess.com-style Brilliant !! moves show up in real games?
// For every move of the chosen games: the full analysis label (analyzeMove) and, for the position before it, which of
// the engine's moves the brilliant lines mark (topMoves.ts addBrilliants, as the "Show best move" list does). Plus the
// near misses: best / near-best moves that leave a piece en prise (analysis/brilliant.ts staticSacrifice) but get no
// Brilliant, and why (classify.ts brilliantCheck).
//
// Games: chess.com monthly archive JSON (https://api.chess.com/pub/player/<name>/games/YYYY/MM) in --dir; the --count
// most recent standard games with at least --min-plies plies. Engine searches are cached in <dir>/cache.sqlite, so a
// rerun after a rule change takes seconds.
//
// Usage: npx tsx bench/brilliants.ts --dir tmp/brilliant [--pgn-dir bench/games/lichess] [--count 25] [--skip 0] [--min-plies 20] [--cache cache.sqlite]
//        [--out tmp/brilliant/report.md]   (--skip / --cache: run shards in parallel, one cache file each)

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DEFAULT_SETTINGS as S, winPercentFromScore, type Label } from '@chess-coach/shared';
import { analyzeMove } from '../core/src/analysis/analyzeMove';
import { brilliantCheck, countLegalMoves, type ClassifyInput } from '../core/src/analysis/classify';
import { staticSacrifice } from '../core/src/analysis/brilliant';
import { SearchCache, type SearchParams } from '../core/src/analysis/searchCache';
import { addBrilliants, pickTopMoves, topParams } from '../core/src/analysis/topMoves';
import { CacheDb } from '../core/src/cache';
import '../core/src/node'; // the opening book from disk
import { Engine } from '../core/src/engine/node';
import type { PvLine } from '../core/src/engine/uci';
import { parseLichessGame } from './lib/lichessPgn';

const args = process.argv.slice(2);
const arg = (name: string, def: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && i + 1 < args.length ? args[i + 1]! : def;
};
const DIR = arg('dir', 'tmp/brilliant');
const COUNT = Number(arg('count', '25'));
const MIN_PLIES = Number(arg('min-plies', '20'));
const SKIP = Number(arg('skip', '0'));
const CACHE = arg('cache', 'cache.sqlite');
const OUT = arg('out', join(DIR, 'report.md'));

interface ChessComGame { url: string; pgn: string; end_time: number; rules: string; time_class: string; white: { username: string; rating: number }; black: { username: string; rating: number } }

const games: ChessComGame[] = [];
for (const f of readdirSync(DIR).filter((x) => /^games-.*\.json$/.test(x))) games.push(...(JSON.parse(readFileSync(join(DIR, f), 'utf8')) as { games: ChessComGame[] }).games);
// --pgn-dir: plain PGN files instead (e.g. bench/games/lichess), in file name order
const PGN_DIR = arg('pgn-dir', '');
if (PGN_DIR) {
  games.length = 0;
  for (const [i, f] of readdirSync(PGN_DIR).filter((x) => x.endsWith('.pgn')).sort().entries()) {
    const pgn = readFileSync(join(PGN_DIR, f), 'utf8');
    const h = (k: string) => new RegExp(`\\[${k} "([^"]*)"\\]`).exec(pgn)?.[1] ?? '?';
    games.push({ url: h('Site'), pgn, end_time: -i, rules: 'chess', time_class: '?', white: { username: h('White'), rating: Number(h('WhiteElo')) }, black: { username: h('Black'), rating: Number(h('BlackElo')) } });
  }
}
const chosen = games
  .filter((g) => g.rules === 'chess' && g.pgn)
  .sort((a, b) => b.end_time - a.end_time)
  .map((g) => ({ g, parsed: parseLichessGame(g.pgn) }))
  .filter((x) => x.parsed.plies.length >= MIN_PLIES)
  .slice(SKIP, SKIP + COUNT);

const engine = await Engine.start({ threads: Number(process.env.BENCH_THREADS ?? 8), hashMb: 256 });
const cache = new SearchCache(new CacheDb(join(DIR, CACHE)));
const search = async (fen: string, p: SearchParams) => (await cache.search(engine, fen, p)).result;

const out: string[] = ['# Brilliant !! benchmark', '', `Generated by bench/brilliants.ts on ${chosen.length} games (${DIR}).`, ''];
const labelled: string[] = [];
const lineMarks: string[] = [];
const nearMiss: string[] = [];
let plies = 0;
const counts: Partial<Record<Label, number>> = {};

const moveNo = (ply: number, color: string) => `${Math.ceil(ply / 2)}${color === 'white' ? '.' : '…'}`;

for (const [gi, { g, parsed }] of chosen.entries()) {
  let prev: { fenBefore: string; uci: string } | null = null;
  let chain = true;
  for (const p of parsed.plies) {
    plies++;
    const a = await analyzeMove({ searcher: engine, cache, settings: S }, { fenBefore: p.fenBefore, uci: p.uci, prev, earlierMovesAllBook: chain });
    counts[a.label] = (counts[a.label] ?? 0) + 1;
    const where = `[game ${SKIP + gi + 1}](${g.url}) ${moveNo(p.ply, p.color)} ${p.san}`;
    const mover = p.color === 'white' ? g.white : g.black;
    if (a.label === 'brilliant') labelled.push(`- ${where} (${mover.username} ${mover.rating}) — ${a.labelReason.brilliant?.piece.role} on ${a.labelReason.brilliant?.piece.square}`);

    // the brilliant lines in the position before the move
    const deep = await search(p.fenBefore, topParams(S));
    const top = await addBrilliants(p.fenBefore, deep, pickTopMoves(p.fenBefore, deep, S), S, prev, search);
    const marks = top.filter((m) => m.brilliant);
    if (marks.length) {
      lineMarks.push(`- ${where.replace(` ${p.san}`, '')} (before ${p.san}): ${marks.map((m) => `${m.san}${m.extra ? ' (extra)' : ''} — ${m.brilliant!.piece.role} ${m.brilliant!.piece.square}`).join('; ')}${marks.some((m) => m.uci === p.uci) ? ' — played' : ''}`);
    }

    // near misses: a best / near-best move that leaves a piece en prise, but no Brilliant
    const st = staticSacrifice(p.fenBefore, p.uci, prev?.fenBefore ?? null);
    const lines = [...deep.lines].sort((x, y) => x.multipv - y.multipv);
    const best = lines[0];
    if (best && a.label !== 'brilliant' && !p.san.includes('#') && !('reject' in st && st.reject === 'no-unsafe-piece')) {
      let played: PvLine | undefined = lines.find((l) => l.move === p.uci);
      if (!played) played = (await search(p.fenBefore, { ...topParams(S), multipv: 1, searchmoves: [p.uci] })).lines[0];
      if (played) {
        const isBest = best.move === p.uci;
        const winPlayed = winPercentFromScore(played.score);
        const winLoss = isBest ? 0 : Math.max(0, winPercentFromScore(best.score) - winPlayed);
        if (winLoss <= 5) {
          const input: ClassifyInput = {
            fenBefore: p.fenBefore,
            legalMoveCount: countLegalMoves(p.fenBefore),
            played: { uci: p.uci, score: played.score, pv: played.pv },
            playedIsBest: isBest,
            best: { uci: best.move, score: best.score, pv: best.pv },
            second: lines[1] ? { uci: lines[1].move, score: lines[1].score, pv: lines[1].pv } : null,
            prev: prev ? { winLoss: 0, winBefore: 50, winAfter: 50, fenBefore: prev.fenBefore, uci: prev.uci } : null,
          };
          const c = brilliantCheck(input, isBest, winPlayed, winLoss, S);
          const why = 'reject' in c ? c.reject : 'passes';
          nearMiss.push(`- ${where}: label ${a.label}, win% after ${winPlayed.toFixed(0)}, loss ${winLoss.toFixed(1)} — ${'reject' in st ? `board: ${st.reject}` : `offers the ${st.piece.role} on ${st.piece.square}`}; rule: ${why}`);
        }
      }
    }
    if (a.label !== 'book') chain = false;
    prev = { fenBefore: p.fenBefore, uci: p.uci };
  }
  process.stdout.write(`game ${gi + 1}/${chosen.length} (${parsed.plies.length} plies)\n`);
}
await engine.quit();

out.push(`Plies: ${plies}. Labels: ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(', ')}.`, '');
out.push(`## Labelled Brilliant (${labelled.length})`, '', ...(labelled.length ? labelled : ['(none)']), '');
out.push(`## Brilliant lines (positions with a marked move: ${lineMarks.length})`, '', ...(lineMarks.length ? lineMarks : ['(none)']), '');
out.push(`## Near misses (${nearMiss.length})`, '', ...(nearMiss.length ? nearMiss : ['(none)']), '');
out.push('## Games', '', ...chosen.map(({ g, parsed }, i) => `${SKIP + i + 1}. ${g.url} — ${g.white.username} (${g.white.rating}) vs ${g.black.username} (${g.black.rating}), ${g.time_class}, ${parsed.plies.length} plies`), '');
writeFileSync(OUT, out.join('\n'));
console.log(`-> ${OUT}`);
