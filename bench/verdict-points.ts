// (Points) Eyeball report for the verdict card of layout A: each move's label, the verdict sentence that stays, and
// its points (MoveAnalysis.points, laid out by client/src/lib/verdict.ts verdictPoints).
//
// Usage: npx tsx bench/verdict-points.ts [--games 3] [--from 1] [--to 40] [--out bench/reports/verdict-points.md]

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_SETTINGS as S, type MoveAnalysis } from '@chess-coach/shared';
import { analyzeMove } from '../core/src/analysis/analyzeMove';
import { SearchCache } from '../core/src/analysis/searchCache';
import '../core/src/node'; // the opening book from disk
import { Engine } from '../core/src/engine/node';
import { moveVerdict, sentenceWithPoints, verdictPoints } from '../client/src/lib/verdict';
import { parseLichessGame } from './lib/lichessPgn';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const arg = (name: string, def: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && i + 1 < args.length ? args[i + 1]! : def;
};
const GAMES = Number(arg('games', '3'));
const FROM = Number(arg('from', '1'));
const TO = Number(arg('to', '40'));
const OUT = arg('out', join(here, 'reports', 'verdict-points.md'));

const dir = join(here, 'games', 'lichess');
const files = readdirSync(dir).filter((f) => f.endsWith('.pgn')).sort().slice(0, GAMES);
const engine = await Engine.start({ threads: Number(process.env.BENCH_THREADS ?? 4), hashMb: 256 });
const cache = new SearchCache(null);
const lines: string[] = ['# Verdict points (eyeball report)', '', 'Generated by bench/verdict-points.ts: label — sentence, then the points under it.', ''];
const tick = (t: string) => (t === 'good' ? '✓' : t === 'bad' ? '✗' : '•');
for (const f of files) {
  const g = parseLichessGame(readFileSync(join(dir, f), 'utf8'));
  lines.push(`## ${f.replace('.pgn', '')} — ${g.headers.White} vs ${g.headers.Black}`, '');
  let prev: { fenBefore: string; uci: string } | null = null;
  for (const p of g.plies) {
    if (p.ply > TO) break;
    const a: MoveAnalysis = await analyzeMove({ searcher: engine, cache, settings: S }, { fenBefore: p.fenBefore, uci: p.uci, prev });
    prev = { fenBefore: p.fenBefore, uci: p.uci };
    if (p.ply < FROM) continue;
    const v = moveVerdict(a, { moverIsYou: false });
    const pts = verdictPoints(a);
    const sentence = sentenceWithPoints(a, v, pts);
    const no = `${Math.ceil(p.ply / 2)}${p.color === 'white' ? '.' : '…'}`;
    const out = [`- **${no} ${a.san}** ${v.name}${sentence ? ` — ${sentence}` : ''}`];
    if (pts?.sameAs) out.push(`  - _same idea as ${pts.sameAs}, the best move${pts.lines.length ? ':' : ' — just a little less precise'}_`);
    for (const l of pts?.lines ?? []) out.push(`  - ${tick(l.tone)} ${l.text}`);
    if (pts?.better) out.push(`  - _best was ${pts.better.san}:_ ${pts.better.lines.map((l) => `${tick(l.tone)} ${l.text}`).join(' · ')}`);
    lines.push(...out);
    process.stdout.write('.');
  }
  lines.push('');
}
await engine.quit();
writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`\n-> ${OUT}`);
