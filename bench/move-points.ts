// (Points) Eyeball report for analysis/movePoints.ts: the engine's top moves in real game positions and what the
// points say about each, plus how often a move gets a reason of its own.
//
// Usage: npx tsx bench/move-points.ts [--games 12] [--every 7] [--from 3] [--to 60] [--out bench/reports/move-points.md]
// Positions: every `every`-th ply (from `from` to `to`) of the first `games` Lichess test games (bench/games/lichess).

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_SETTINGS as S, type MoveIdea } from '@chess-coach/shared';
import { SearchCache, type SearchParams } from '../core/src/analysis/searchCache';
import { pickTopMoves, topParams } from '../core/src/analysis/topMoves';
import { topIdeas } from '../core/src/analysis/movePoints';
import { formatEval } from '../core/src/analysis/explain';
import { Engine } from '../core/src/engine/node';
import { parseLichessGame } from './lib/lichessPgn';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const arg = (name: string, def: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && i + 1 < args.length ? args[i + 1]! : def;
};
const GAMES = Number(arg('games', '12'));
const EVERY = Number(arg('every', '7'));
const FROM = Number(arg('from', '3'));
const TO = Number(arg('to', '60'));
const OUT = arg('out', join(here, 'reports', 'move-points.md'));

const dir = join(here, 'games', 'lichess');
const files = readdirSync(dir).filter((f) => f.endsWith('.pgn')).sort().slice(0, GAMES);
const engine = await Engine.start({ threads: Number(process.env.BENCH_THREADS ?? 4), hashMb: 256 });
const cache = new SearchCache(null);
const search = async (fen: string, p: SearchParams) => (await cache.search(engine, fen, p)).result;

const lines: string[] = ['# Move points (eyeball report)', '', `Settings: deep depth ${S.budget.deep.depth}, top moves up to 8 (Good range). Generated by bench/move-points.ts.`, ''];
let moves = 0;
let withOwn = 0;
let liked = 0;
let planOnly = 0;
let nothing = 0;
const t0 = Date.now();
for (const f of files) {
  const g = parseLichessGame(readFileSync(join(dir, f), 'utf8'));
  lines.push(`## ${f.replace('.pgn', '')} — ${g.headers.White} vs ${g.headers.Black} (${g.headers.Opening ?? ''})`, '');
  for (const p of g.plies) {
    if (p.ply < FROM || p.ply > TO || (p.ply - FROM) % EVERY !== 0) continue;
    const r = await search(p.fenBefore, topParams(S));
    const top = pickTopMoves(p.fenBefore, r, S);
    const ideas: MoveIdea[] = await topIdeas(p.fenBefore, top, r.lines, S, search);
    const moveNo = `${Math.ceil(p.ply / 2)}${p.color === 'white' ? '.' : '…'}`;
    lines.push(`### Ply ${p.ply} (${moveNo}, ${p.color} to move; played ${p.san})`, '', `\`${p.fenBefore}\``, '');
    for (const [i, m] of ideas.entries()) {
      moves++;
      const t = top[i]!;
      const head = `${i + 1}. **${m.san}** (${formatEval(t.score)}, −${t.winLoss}%)`;
      let body: string;
      if (m.like !== undefined) {
        liked++;
        const diff = [...(m.plus ?? []).map((x) => `+ ${x.text}`), ...(m.minus ?? []).map((x) => `− ${x.text}`)];
        body = `same idea as ${ideas[m.like]!.san}${diff.length ? ': ' + diff.join(' · ') : ' (just a little less precise)'}`;
      } else if (m.points.length) {
        body = m.points.map((x) => `${x.tone === 'good' ? '✓' : x.tone === 'bad' ? '✗' : '•'} ${x.text}`).join(' · ');
      } else body = '—';
      if (m.like === undefined && m.points.some((x) => x.tone !== 'bad')) withOwn++;
      if (m.plan?.length) {
        body += ` _(plan: ${m.plan.join(', ')})_`;
        if (!m.points.some((x) => x.tone !== 'bad') && m.like === undefined) planOnly++;
      }
      if (!m.points.length && m.like === undefined && !m.plan?.length) nothing++;
      lines.push(`${head} — ${body}`);
    }
    lines.push('');
    process.stdout.write('.');
  }
}
await engine.quit();
const pct = (n: number) => `${Math.round((100 * n) / Math.max(1, moves))}%`;
lines.splice(4, 0, `**${moves} moves**: own good point ${withOwn} (${pct(withOwn)}), same idea as a better move ${liked} (${pct(liked)}), only a plan ${planOnly} (${pct(planOnly)}), nothing ${nothing} (${pct(nothing)}). ${Math.round((Date.now() - t0) / 1000)} s.`, '');
writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`\n${lines[4]}\n-> ${OUT}`);
